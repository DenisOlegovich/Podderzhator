function assertDimensions(): void {
  if (OPEN_PAIRS.length * CLOSES.length !== SUPPORT_PHRASE_COUNT) {
    throw new Error(
      `support-phrases: ожидалось ${SUPPORT_PHRASE_COUNT} комбинаций, получилось ${OPEN_PAIRS.length * CLOSES.length}`,
    )
  }
}

assertDimensions()

/** Индекс 0..776 → пара (открытие, продолжение). */
export function phraseAt(index: number, gender: SupportPhraseGender): string {
  const i = ((index % SUPPORT_PHRASE_COUNT) + SUPPORT_PHRASE_COUNT) % SUPPORT_PHRASE_COUNT
  const oi = i % OPEN_PAIRS.length
  const ci = (i / OPEN_PAIRS.length) | 0
  const pair = OPEN_PAIRS[oi]!
  const open = gender === 'male' ? pair[0] : pair[1]
  const close = CLOSES[ci]!
  const needsComma = !/[,—…]\s*$/.test(open)
  return needsComma ? `${open}, ${close}` : `${open} ${close}`
}
